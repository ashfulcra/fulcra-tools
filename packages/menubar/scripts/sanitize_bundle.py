"""Remove build-only entry points and reject local paths before app signing."""
from pathlib import Path
import argparse
import shutil
import os


def _test_only_payloads(packages: Path) -> list[Path]:
    """Return dependency test code that the installed app cannot execute.

    Several binary wheels ship their entire upstream test suites.  They are
    useful to dependency maintainers but add tens of megabytes to Collect's
    signed app.  Keep public runtime helpers such as ``numpy.testing``; remove
    only directories named ``tests`` and the known top-level pytest/PyObjC test
    packages installed by Collect's dependency graph.
    """
    candidates = [
        packages / 'PyObjCTest',
        packages / '_pytest',
        packages / 'pytest',
        packages / '.pytest_cache',
        *packages.glob('pytest-*.dist-info'),
        *packages.glob('pytest_mock-*.dist-info'),
        *packages.rglob('tests'),
        *packages.glob('pyarrow/_pyarrow_cpp_tests.*'),
    ]
    return sorted(
        {path for path in candidates if path.exists() or path.is_symlink()},
        key=lambda path: (len(path.parts), str(path)),
        reverse=True,
    )


def _cleanup(app: Path, *, check_only: bool = False) -> None:
    packages = app / 'Contents' / 'Resources' / 'app_packages'
    if (not packages.is_dir() or any(p.is_symlink() for p in
            (app, app / 'Contents', app / 'Contents/Resources', packages))):
        raise RuntimeError('Expected a built application with bundled packages')
    scripts = packages / 'bin'
    if scripts.is_symlink():
        raise RuntimeError('Refusing a symlinked package script directory')
    if scripts.exists():
        # Pip embeds its build-interpreter path in these shebangs. They are
        # unusable after installation; signed native launchers live in MacOS/.
        if check_only:
            raise RuntimeError('Nonportable package scripts remain in bundle')
        shutil.rmtree(scripts)
    test_payloads = _test_only_payloads(packages)
    if any(any(parent.is_symlink() for parent in (path, *path.parents)
               if parent != packages and packages in parent.parents)
           or not path.resolve().is_relative_to(packages.resolve())
           for path in test_payloads):
        raise RuntimeError('Refusing symlinked test-only payload in bundle')
    if test_payloads and check_only:
        raise RuntimeError('Test-only payloads remain in bundle')
    for path in test_payloads:
        if path.is_dir():
            shutil.rmtree(path)
        elif path.exists():
            path.unlink()
    # Imports performed while assembling or verifying the app can write .pyc
    # files after pip has installed otherwise portable source. Python embeds the
    # compiler's source filename in that bytecode, which can disclose the build
    # machine's home directory. Bytecode is optional at runtime, so remove every
    # generated cache immediately before signing and fail closed in check mode.
    cache_dirs = sorted(packages.rglob('__pycache__'), reverse=True)
    bytecode = [
        path for suffix in ('*.pyc', '*.pyo') for path in packages.rglob(suffix)
    ]
    loose_bytecode = [path for path in bytecode if '__pycache__' not in path.parts]
    generated = cache_dirs + bytecode
    if any(path.is_symlink() for path in generated):
        raise RuntimeError('Refusing symlinked generated bytecode in bundle')
    if generated and check_only:
        raise RuntimeError('Generated bytecode remains in bundle')
    for path in cache_dirs:
        if path.exists():
            shutil.rmtree(path)
    for path in loose_bytecode:
        if path.exists():
            path.unlink()


def sanitize(app: Path, *, home: Path | None = None, check_only: bool = False,
             phase: str = 'raw', provenance_receipt: Path | None = None,
             expected=None, markers: tuple[str, ...] | None = None):
    from bundle_provenance import scan_bundle
    if provenance_receipt is not None or expected is not None:
        from bundle_provenance_stages import ReceiptRef, sanitize_stage
        if expected is None or provenance_receipt is None:
            raise RuntimeError('UNKNOWN: independent current invocation/head required')
        if Path(app).absolute() != expected.app:
            raise RuntimeError('UNKNOWN: independent app scope differs')
        head = expected.head
        ref = ReceiptRef(Path(provenance_receipt).absolute(), head.digest, head.generation, head.stage, head.predecessor)
        return sanitize_stage(expected, ref, phase=phase, check_only=check_only)
    if phase != 'raw':
        raise RuntimeError('UNKNOWN: transformed phase requires current provenance authority')
    _cleanup(app, check_only=check_only)
    selected_markers = markers or tuple(dict.fromkeys(value for value in
        (str(home or Path.home()), os.environ.get('COLLECT_QA_ROOT'), os.environ.get('RUNNER_TEMP')) if value))
    result = scan_bundle(app, selected_markers)
    if result.status != 'COMPLETE' or result.privacy_rejections:
        raise RuntimeError(f'Personal home path remains in {result.privacy_rejections} bundle entries or scan is UNKNOWN; paths are redacted')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('app', type=Path)
    parser.add_argument('--check-only', action='store_true')
    parser.add_argument('--phase', choices=('raw', 'postbuild', 'signed'), default='raw')
    parser.add_argument('--provenance-receipt', type=Path)
    args = parser.parse_args()
    try:
        if args.provenance_receipt is not None:
            from bundle_provenance_stages import expected_from_environment, advance, context_json
            expected = expected_from_environment()
            if args.app.absolute() != expected.app:
                raise RuntimeError('UNKNOWN: app scope differs from current invocation')
            ref = sanitize(args.app, check_only=args.check_only, phase=args.phase,
                           provenance_receipt=args.provenance_receipt, expected=expected)
            print(context_json(advance(expected, ref)))
        else:
            sanitize(args.app, check_only=args.check_only, phase=args.phase)
    except RuntimeError:
        parser.exit(1, 'UNKNOWN: privacy/provenance check failed; paths are redacted\n')
